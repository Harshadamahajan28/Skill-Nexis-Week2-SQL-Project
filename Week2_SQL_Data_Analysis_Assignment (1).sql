-- Skill Nexis Week 2: SQL for Data Analysis
-- Dataset: Global Superstore 2016
-- Tables: customers, orders
-- Assignment: Top Customers and Average Order Value
-- Includes SELECT, WHERE, GROUP BY, ORDER BY, SUM, AVG, COUNT,
-- JOIN, subqueries, and CASE statements.

-- ============================================================
-- 1. BASIC SELECT
-- ============================================================
SELECT * FROM orders
LIMIT 10;

-- ============================================================
-- 2. WHERE
-- ============================================================
SELECT Order_ID, Order_Date, Customer_ID, Category, Sales
FROM orders
WHERE Sales > 500
ORDER BY Sales DESC;

-- ============================================================
-- 3. GROUP BY + SUM
-- Total sales by category
-- ============================================================
SELECT Category,
       SUM(Sales) AS Total_Sales
FROM orders
GROUP BY Category
ORDER BY Total_Sales DESC;

-- ============================================================
-- 4. COUNT
-- Number of orders
-- ============================================================
SELECT COUNT(DISTINCT Order_ID) AS Total_Orders
FROM orders;

-- ============================================================
-- 5. AVG
-- Average line-item sales value
-- ============================================================
SELECT ROUND(AVG(Sales), 2) AS Average_Sales
FROM orders;

-- ============================================================
-- 6. TOP CUSTOMERS
-- Total sales generated by each customer
-- ============================================================
SELECT c.Customer_ID,
       c.Customer_Name,
       ROUND(SUM(o.Sales), 2) AS Total_Sales
FROM customers c
JOIN orders o
  ON c.Customer_ID = o.Customer_ID
GROUP BY c.Customer_ID, c.Customer_Name
ORDER BY Total_Sales DESC
LIMIT 10;

-- ============================================================
-- 7. AVERAGE ORDER VALUE
-- First calculate each order total, then take the average.
-- ============================================================
SELECT ROUND(AVG(Order_Total), 2) AS Average_Order_Value
FROM (
    SELECT Order_ID,
           SUM(Sales) AS Order_Total
    FROM orders
    GROUP BY Order_ID
) AS order_totals;

-- ============================================================
-- 8. JOIN
-- Customer-wise order count and revenue
-- ============================================================
SELECT c.Customer_Name,
       COUNT(DISTINCT o.Order_ID) AS Number_of_Orders,
       ROUND(SUM(o.Sales), 2) AS Total_Revenue
FROM customers c
JOIN orders o
  ON c.Customer_ID = o.Customer_ID
GROUP BY c.Customer_ID, c.Customer_Name
ORDER BY Total_Revenue DESC;

-- ============================================================
-- 9. SUBQUERY
-- Orders whose sales are above the overall average sales
-- ============================================================
SELECT Order_ID, Product_Name, Sales
FROM orders
WHERE Sales > (SELECT AVG(Sales) FROM orders)
ORDER BY Sales DESC;

-- ============================================================
-- 10. CASE STATEMENT
-- Classify sales into performance groups
-- ============================================================
SELECT Order_ID,
       Sales,
       CASE
           WHEN Sales >= 1000 THEN 'High'
           WHEN Sales >= 500 THEN 'Medium'
           ELSE 'Low'
       END AS Sales_Level
FROM orders
ORDER BY Sales DESC;

-- ============================================================
-- 11. YEARLY SALES
-- ============================================================
SELECT strftime('%Y', Order_Date) AS Year,
       ROUND(SUM(Sales), 2) AS Total_Sales
FROM orders
GROUP BY strftime('%Y', Order_Date)
ORDER BY Year;

-- ============================================================
-- 12. CATEGORY + AVERAGE ORDER/LINE SALES
-- ============================================================
SELECT Category,
       COUNT(*) AS Number_of_Rows,
       ROUND(AVG(Sales), 2) AS Average_Sales,
       ROUND(SUM(Sales), 2) AS Total_Sales
FROM orders
GROUP BY Category
ORDER BY Total_Sales DESC;
